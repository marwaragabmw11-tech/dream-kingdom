  (window.UNITS || []).forEach((u, ui) => (u.lessons || []).forEach((l, li) => { const e = (window.LEARN_EN || [])[ui] && window.LEARN_EN[ui][li]; if (e) { l.E = e; if (e.tryS && l.try) l.try.e = e.tryS; } }));
